import assert from 'node:assert/strict';
import { copyFile, mkdir, mkdtemp, readFile, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';
import { REVIEWED_NODE_VERSION, REVIEWED_NPM_VERSION, writeHandoffManifest } from './lockfile-handoff-manifest.mjs';
import { adoptLockfileHandoff, verifyAdoptionCandidate } from './adopt-lockfile-handoff.mjs';

const COMMIT = '0123456789abcdef0123456789abcdef01234567';
const REF = 'refs/heads/project/device-bridge';

async function fixture() {
  const base = await mkdtemp(path.join(os.tmpdir(), 'bridge-adopt-lockfiles-'));
  const generated = path.join(base, 'generated');
  const source = path.join(base, 'source');
  const artifact = path.join(base, 'artifact');
  for (const directory of [generated, source, artifact]) {
    await mkdir(path.join(directory, 'server'), { recursive: true });
  }

  const files = new Map([
    ['package.json', '{"name":"bridge"}\n'],
    ['server/package.json', '{"name":"server"}\n'],
    ['package-lock.json', '{"lockfileVersion":3,"name":"bridge"}\n'],
    ['server/package-lock.json', '{"lockfileVersion":3,"name":"server"}\n'],
  ]);
  for (const [relativePath, content] of files) {
    await writeFile(path.join(generated, relativePath), content);
  }
  await writeFile(path.join(source, 'package.json'), files.get('package.json'));
  await writeFile(path.join(source, 'server/package.json'), files.get('server/package.json'));

  await writeHandoffManifest({
    rootDir: generated,
    outputPath: path.join(generated, 'lockfile-handoff-manifest.json'),
    commit: COMMIT,
    ref: REF,
    nodeVersion: REVIEWED_NODE_VERSION,
    npmVersion: REVIEWED_NPM_VERSION,
  });
  for (const relativePath of ['package-lock.json', 'server/package-lock.json', 'lockfile-handoff-manifest.json']) {
    await copyFile(path.join(generated, relativePath), path.join(artifact, relativePath));
  }
  return { source, artifact };
}

test('adopts an exact source-bound lockfile pair', async () => {
  const { source, artifact } = await fixture();
  await adoptLockfileHandoff({ sourceRoot: source, artifactRoot: artifact, commit: COMMIT, ref: REF });
  assert.match(await readFile(path.join(source, 'package-lock.json'), 'utf8'), /bridge/);
  assert.match(await readFile(path.join(source, 'server/package-lock.json'), 'utf8'), /server/);
});

test('rejects a handoff bound to another source manifest', async () => {
  const { source, artifact } = await fixture();
  await writeFile(path.join(source, 'package.json'), '{"name":"changed"}\n');
  await assert.rejects(
    verifyAdoptionCandidate({ sourceRoot: source, artifactRoot: artifact, commit: COMMIT, ref: REF }),
    /mismatch for package\.json/,
  );
});

test('rejects a handoff from another source commit', async () => {
  const { source, artifact } = await fixture();
  await assert.rejects(
    verifyAdoptionCandidate({
      sourceRoot: source,
      artifactRoot: artifact,
      commit: 'fedcba9876543210fedcba9876543210fedcba98',
      ref: REF,
    }),
    /commit mismatch/,
  );
});

test('rejects a handoff generated by another Node 22 release', async () => {
  const { source, artifact } = await fixture();
  const manifestPath = path.join(artifact, 'lockfile-handoff-manifest.json');
  const parsed = JSON.parse(await readFile(manifestPath, 'utf8'));
  parsed.generator.nodeVersion = 'v22.22.0';
  await writeFile(manifestPath, JSON.stringify(parsed));
  await assert.rejects(
    verifyAdoptionCandidate({ sourceRoot: source, artifactRoot: artifact, commit: COMMIT, ref: REF }),
    /reviewed Node v22\.23\.2/,
  );
});

test('refuses to overwrite an existing repository lockfile', async () => {
  const { source, artifact } = await fixture();
  await writeFile(path.join(source, 'package-lock.json'), 'existing');
  await assert.rejects(
    adoptLockfileHandoff({ sourceRoot: source, artifactRoot: artifact, commit: COMMIT, ref: REF }),
    /Refusing to overwrite/,
  );
});
